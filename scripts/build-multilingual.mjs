#!/usr/bin/env node
import fs from "node:fs";
import path from "node:path";
import {
  MEMORY_PATH,
  OUT_DIR,
  PUBLIC_MEMORY_PATH,
  readMemory,
} from "./i18n.mjs";

if (!fs.existsSync(OUT_DIR)) {
  console.error("Missing out/. Run next build before multilingual postprocessing.");
  process.exit(1);
}

const memory = readMemory();
syncPublicMemory(memory);

// Next.js generates the locale routes itself. Rewriting their emitted HTML
// would make it disagree with the React payload used for hydration, which
// disables client-side interactions on translated pages.
console.log("Translation memory copied for the locale routes generated by Next.js.");

function syncPublicMemory(memory) {
  const serialized = `${JSON.stringify(memory, null, 2)}\n`;
  fs.mkdirSync(path.dirname(PUBLIC_MEMORY_PATH), { recursive: true });
  fs.mkdirSync(path.join(OUT_DIR, "i18n"), { recursive: true });
  fs.writeFileSync(PUBLIC_MEMORY_PATH, serialized);
  fs.writeFileSync(path.join(OUT_DIR, "i18n", "translation-memory.json"), serialized);
  if (!fs.existsSync(MEMORY_PATH)) fs.writeFileSync(MEMORY_PATH, serialized);
}
